    #[test]
    fn block_schema_members_match_the_loader_authority() -> Result<(), String> {
        let (command_registry, condition_registry) = registries()?;
        let schema = generated_schema(&command_registry, &condition_registry)?;
        let properties = value_field(block_schema(&schema)?, "properties")?
            .as_object()
            .ok_or_else(|| String::from("block properties are not an object"))?;
        let mut schema_members = properties.keys().map(String::as_str).collect::<Vec<_>>();
        let mut recognized_members = RECOGNIZED_BLOCK_MEMBERS.to_vec();

        schema_members.sort_unstable();
        recognized_members.sort_unstable();

        assert_eq!(schema_members, recognized_members);
        assert!(
            properties
                .values()
                .all(serde_json_lenient::Value::is_object)
        );

        Ok(())
    }

