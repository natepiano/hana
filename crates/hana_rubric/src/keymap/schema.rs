    fn registries() -> Result<(CommandRegistry, ConditionRegistry), String> {
        let mut type_registry = TypeRegistry::default();
        type_registry.register::<CameraHome>();
        type_registry.register::<CameraMove>();
        type_registry.register::<RecoveryOpen>();
        let mut custom_inputs = CustomInputs::default();
        let command_registry = CommandRegistry::build(&type_registry, &mut custom_inputs)
            .map_err(|diagnostics| format!("command registry errors: {diagnostics:?}"))?;
        let mut condition_registry = ConditionRegistry::default();
        condition_registry
            .register::<TestContext>()
            .map_err(|diagnostics| format!("condition registry errors: {diagnostics:?}"))?;

        Ok((command_registry, condition_registry))
    }

    fn generated_schema(
        command_registry: &CommandRegistry,
        condition_registry: &ConditionRegistry,
    ) -> Result<Value, String> {
        let bytes = keymap::schema_bytes(command_registry, condition_registry)
            .map_err(|error| format!("schema serialization error: {error}"))?;

        serde_json_lenient::from_slice(&bytes)
            .map_err(|error| format!("schema JSON parse error: {error}"))
    }

    fn value_field<'value>(value: &'value Value, field: &str) -> Result<&'value Value, String> {
        value
            .get(field)
            .ok_or_else(|| format!("schema is missing `{field}`"))
    }

    fn value_array<'value>(value: &'value Value, field: &str) -> Result<&'value [Value], String> {
        value_field(value, field)?
            .as_array()
            .map(Vec::as_slice)
            .ok_or_else(|| format!("schema `{field}` is not an array"))
    }

    fn block_schema(schema: &Value) -> Result<&Value, String> {
        value_field(
            value_field(value_field(schema, "properties")?, "bindings")?,
            "items",
        )
    }

    fn binding_value_schema(schema: &Value) -> Result<&Value, String> {
        value_field(
            value_field(block_schema(schema)?, "properties")?
                .get("bindings")
                .ok_or_else(|| String::from("block schema is missing `bindings`"))?,
            "additionalProperties",
        )
    }

    fn alternatives_with_type<'schema>(
        schema: &'schema Value,
        value_type: &str,
    ) -> Result<Vec<&'schema Value>, String> {
        Ok(value_array(schema, "anyOf")?
            .iter()
            .filter(|alternative| {
                alternative
                    .get("type")
                    .and_then(serde_json_lenient::Value::as_str)
                    == Some(value_type)
            })
            .collect())
    }

    fn alternative_for_const<'value>(
        alternatives: &'value [Value],
        constant: &str,
    ) -> Result<&'value Value, String> {
        alternatives
            .iter()
            .find(|alternative| {
                alternative
                    .get("const")
                    .and_then(serde_json_lenient::Value::as_str)
                    == Some(constant)
            })
            .ok_or_else(|| format!("schema has no completion for `{constant}`"))
    }

    fn draft_seven_validator(schema: &Value) -> Result<Validator, String> {
        let schema = serde_json::to_value(schema)
            .map_err(|error| format!("schema JSON conversion error: {error}"))?;

        jsonschema::draft7::new(&schema)
            .map_err(|error| format!("Draft-07 schema compilation error: {error}"))
    }

    fn jsonc_document(source: &str) -> Result<serde_json::Value, String> {
        serde_json_lenient::from_str::<serde_json::Value>(source)
            .map_err(|error| format!("keymap JSONC parse error: {error}"))
    }

    #[test]
    fn schema_is_valid_json_with_draft_seven_document_members() -> Result<(), String> {
        let (command_registry, condition_registry) = registries()?;
        let schema = generated_schema(&command_registry, &condition_registry)?;

        assert_eq!(
            value_field(&schema, "$schema")?.as_str(),
            Some("http://json-schema.org/draft-07/schema#")
        );
        assert!(value_field(&schema, "description")?.is_string());
        assert_eq!(value_field(&schema, "type")?.as_str(), Some("object"));
        assert!(value_field(&schema, "properties")?.is_object());
        assert!(value_array(&schema, "required")?.contains(&serde_json_lenient::json!("bindings")));

        Ok(())
    }

    #[test]
    fn every_user_bindable_command_and_condition_has_a_described_completion() -> Result<(), String>
    {
        let (command_registry, condition_registry) = registries()?;
        let schema = generated_schema(&command_registry, &condition_registry)?;
        let command_alternatives = value_array(binding_value_schema(&schema)?, "anyOf")?;
        let condition_schema = value_field(
            value_field(block_schema(&schema)?, "properties")?,
            "context",
        )?;
        let condition_alternatives = value_array(condition_schema, "anyOf")?;

        for command in command_registry
            .iter()
            .filter(|command| command.capability.is_user_bindable())
        {
            let alternative = alternative_for_const(command_alternatives, command.id.as_str())?;
            let description = value_field(alternative, "description").and_then(|description| {
                description
                    .as_str()
                    .ok_or_else(|| String::from("command completion description is not text"))
            })?;

            assert!(!description.is_empty());
            assert!(description.starts_with(command.description));
            if command.capability == Capability::Held {
                assert!(description.contains("one keystroke only"));
            }
        }

        for condition in condition_registry.iter() {
            let alternative =
                alternative_for_const(condition_alternatives, condition.name.as_str())?;
            assert_eq!(
                value_field(alternative, "description")?.as_str(),
                Some(condition.description)
            );
        }

        assert!(
            alternative_for_const(command_alternatives, "recovery::open").is_err(),
            "unremappable commands must not appear in completion"
        );

        Ok(())
    }

    #[test]
    fn null_is_a_described_binding_tombstone() -> Result<(), String> {
        let (command_registry, condition_registry) = registries()?;
        let schema = generated_schema(&command_registry, &condition_registry)?;
        let validator = draft_seven_validator(&schema)?;
        let binding_value_schema = binding_value_schema(&schema)?;
        let null_alternative =
            alternatives_with_type(binding_value_schema, "null").and_then(|alternatives| {
                alternatives
                    .into_iter()
                    .next()
                    .ok_or_else(|| String::from("schema has no null binding alternative"))
            })?;
        let document = jsonc_document(
            r#"{
                "bindings": [{
                    "bindings": { "ctrl-k": null }
                }]
            }"#,
        )?;

        assert!(
            value_field(null_alternative, "description")?
                .as_str()
                .is_some_and(|description| description.contains("inert"))
        );
        assert!(
            validator.is_valid(&document),
            "null binding tombstone should be accepted"
        );

        Ok(())
    }

